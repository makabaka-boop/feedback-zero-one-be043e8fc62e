"""End-to-end CLI tests, including atomic output replacement and the
independent binary fixtures stored under tests/fixtures/."""

import json
import os
import subprocess
import sys
import tempfile
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from frame_builder import headers, continuation, data_frame, rst  # noqa
from h2audit.framing import FramingError  # noqa
from h2audit.hpack import HpackError  # noqa
from h2audit import audit  # noqa

FIX = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fixtures")


def run_cli(input_path, output_path=None):
    launcher = os.path.join(ROOT, "h2audit_cli.py")
    cmd = [sys.executable, "-I", launcher, input_path]
    if output_path is not None:
        cmd += ["-o", output_path]
    return subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)


class CliTests(unittest.TestCase):

    def setUp(self):
        self.tmp = tempfile.mkdtemp()

    def test_stdout_success(self):
        path = os.path.join(self.tmp, "in.bin")
        with open(path, "wb") as fh:
            fh.write(headers(1, bytes.fromhex("4001780161")))
        proc = run_cli(path)
        self.assertEqual(proc.returncode, 0, proc.stderr)
        self.assertEqual(json.loads(proc.stdout),
                         [[1, 0, [["78", "61"]]]])

    def test_atomic_output_replaces_old_file_on_success(self):
        in_path = os.path.join(self.tmp, "in.bin")
        out_path = os.path.join(self.tmp, "out.json")
        with open(in_path, "wb") as fh:
            fh.write(headers(1, b"\x82"))
        with open(out_path, "w") as fh:
            fh.write("OLD-CONTENT")
        proc = run_cli(in_path, out_path)
        self.assertEqual(proc.returncode, 0, proc.stderr)
        with open(out_path) as fh:
            self.assertNotIn("OLD-CONTENT", fh.read())

    def test_failure_keeps_old_file_and_nonzero_exit(self):
        in_path = os.path.join(self.tmp, "bad.bin")
        out_path = os.path.join(self.tmp, "out.json")
        with open(in_path, "wb") as fh:
            fh.write(headers(1, b"\x80"))  # index 0 -> HPACK error
        with open(out_path, "w") as fh:
            fh.write("OLD-CONTENT")
        proc = run_cli(in_path, out_path)
        self.assertEqual(proc.returncode, 1)
        self.assertIn("rejected", proc.stderr)
        with open(out_path) as fh:
            self.assertEqual(fh.read(), "OLD-CONTENT")
        # no temp files left behind
        self.assertEqual(
            [n for n in os.listdir(self.tmp) if n.startswith(".h2audit-")],
            [],
        )

    def test_empty_file_outputs_empty_array(self):
        path = os.path.join(self.tmp, "empty.bin")
        open(path, "wb").close()
        proc = run_cli(path)
        self.assertEqual(proc.returncode, 0, proc.stderr)
        self.assertEqual(json.loads(proc.stdout), [])

    def test_stderr_mentions_offset(self):
        path = os.path.join(self.tmp, "trunc.bin")
        with open(path, "wb") as fh:
            fh.write(headers(1, b"\x82") + b"\x00\x00\x05\x00")
        proc = run_cli(path)
        self.assertEqual(proc.returncode, 1)
        # the second frame starts right after the first 10-byte frame
        self.assertIn("byte 10", proc.stderr)


class IndependentFixtureTests(unittest.TestCase):
    """The fixtures directory holds standalone binary files generated by
    tests/fixtures/build_fixtures.py; they never depend on hpack.  These
    tests pin the documented offsets and rejection behaviour."""

    def test_valid_fixture(self):
        path = os.path.join(FIX, "valid_cross_frames.bin")
        with open(path, "rb") as fh:
            data = fh.read()
        got = audit(data)
        # Stream 1 block starts at byte 0 and spans HEADERS + CONTINUATION.
        self.assertEqual(got[0],
                         [1, 0, [["78", "61"], ["78", "61"]]])
        # The second HEADERS starts after the first two 9-byte frame
        # headers and their 5+1 payload bytes: 9+5 + 9+1 = 24.
        self.assertEqual(got[1][0], 3)
        self.assertEqual(got[1][1], 24)
        self.assertEqual(got[1][2], [["78", "61"]])
        # DATA(15) + RST(13) come next; stream 5 block starts at 34+15+13
        self.assertEqual(got[2], [5, 62, [["3a6d6574686f64", "474554"]]])

    def test_reject_fixture_unknown_frame(self):
        with open(os.path.join(FIX, "rej_unknown_frame.bin"), "rb") as fh:
            with self.assertRaises(FramingError) as ctx:
                audit(fh.read())
        self.assertEqual(ctx.exception.offset, 0)

    def test_reject_fixture_length_cap(self):
        with open(os.path.join(FIX, "rej_length_cap.bin"), "rb") as fh:
            with self.assertRaises(FramingError) as ctx:
                audit(fh.read())
        self.assertEqual(ctx.exception.offset, 0)

    def test_reject_fixture_continuation_eof(self):
        with open(os.path.join(FIX, "rej_continuation_eof.bin"), "rb") as fh:
            with self.assertRaises(FramingError) as ctx:
                audit(fh.read())
        self.assertEqual(ctx.exception.offset, 0)

    def test_reject_fixture_bad_index_offset(self):
        with open(os.path.join(FIX, "rej_bad_index.bin"), "rb") as fh:
            data = fh.read()
        # first frame is a complete 10-byte legal block; bad block after
        with self.assertRaises(HpackError) as ctx:
            audit(data)
        self.assertEqual(ctx.exception.offset, 10)

    def test_reject_fixture_huffman_eos(self):
        with open(os.path.join(FIX, "rej_huffman_eos.bin"), "rb") as fh:
            with self.assertRaises(HpackError):
                audit(fh.read())


if __name__ == "__main__":
    unittest.main()
